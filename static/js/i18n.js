const urlParams = new URLSearchParams(window.location.search);
const langParam = urlParams.get("lang");
let currentLang = (langParam && i18nData[langParam]) ? langParam : (localStorage.getItem("lakshya_lang") || "en");
if (langParam && i18nData[langParam]) {
  localStorage.setItem("lakshya_lang", langParam);
}

function t(key) {
  if (i18nData[currentLang] && i18nData[currentLang][key]) {
    return i18nData[currentLang][key];
  }
  return i18nData["en"][key] || key;
}

function setLanguage(lang) {
  if (i18nData[lang]) {
    currentLang = lang;
    localStorage.setItem("lakshya_lang", lang);
    applyTranslations();
    if (window.renderAllCharts) {
      window.renderAllCharts();
    }
  }
}

function applyTranslations() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    el.innerText = t(key);
  });
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    const key = el.getAttribute("data-i18n-html");
    el.innerHTML = t(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    el.setAttribute("placeholder", t(key));
  });
  const langSelect = document.getElementById("langSelector");
  if (langSelect) {
    langSelect.value = currentLang;
  }
}

document.addEventListener("DOMContentLoaded", () => {
  applyTranslations();
});
